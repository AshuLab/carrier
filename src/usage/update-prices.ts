// Refreshes prices.generated.ts from LiteLLM's price table (https://github.com/BerriAI/litellm, MIT; see THIRD-PARTY-NOTICES.md):
//   pnpm prices:update
// Keeps the chat models of the providers the harnesses use, normalized as `normalizeModel` does, in US dollars per million tokens.
import { writeFileSync } from 'node:fs';
import { normalizeModel } from './pricing.ts';

const url = 'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json';
// the maker's own entry wins over a cloud's copy of the same model
const providers = ['anthropic', 'openai', 'gemini', 'azure_ai', 'azure', 'vertex_ai-language-models', 'vertex_ai-anthropic_models'];

interface Entry {
  litellm_provider?: string;
  mode?: string;
  input_cost_per_token?: number;
  output_cost_per_token?: number;
  cache_read_input_token_cost?: number;
  cache_creation_input_token_cost?: number;
}

const response = await fetch(url);
if (response.ok === false) throw new Error(`LiteLLM's price table answered ${response.status}`);
const table = (await response.json()) as Record<string, Entry>;
const perMillion = (cost: number) => Number((cost * 1e6).toPrecision(6));

const rates = new Map<string, [number, number, number, number]>();
for (const provider of providers) {
  for (const [key, entry] of Object.entries(table)) {
    const { input_cost_per_token: input, output_cost_per_token: output } = entry;
    if (entry.litellm_provider !== provider || (entry.mode !== 'chat' && entry.mode !== 'responses')) continue;
    if (typeof input !== 'number' || typeof output !== 'number') continue;
    const id = normalizeModel(key);
    // a regional copy (`eu/…`) keeps its prefix after normalizing and is not a model name the CLIs report
    if (id.includes('/') || rates.has(id)) continue;
    // [input, cached read, cache write, output]; a cache the model does not price is read and written at the input price
    rates.set(id, [perMillion(input), perMillion(entry.cache_read_input_token_cost ?? input), perMillion(entry.cache_creation_input_token_cost ?? input), perMillion(output)]);
  }
}

const body = [...rates].sort(([a], [b]) => a.localeCompare(b)).map(([id, r]) => `  '${id}': [${r.join(', ')}],`).join('\n');
writeFileSync(
  new URL('./prices.generated.ts', import.meta.url),
  `// Generated by update-prices.ts on ${new Date().toISOString().slice(0, 10)} from ${url}\n// LiteLLM (BerriAI/litellm), MIT. US dollars per million tokens: [input, cached read, cache write, output].\nexport const litellmPrices: Readonly<Record<string, readonly [number, number, number, number]>> = {\n${body}\n};\n`,
);
console.log(`${rates.size} models written`);
