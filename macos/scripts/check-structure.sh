#!/bin/bash
# Checks the structure rules the tree already meets (spec: docs/specs/macos-app-as-the-base-for-a-web-front-end.md, section 9).
# Greps, not a parser: a false alarm is fixed by renaming or by the rule's ignore list, not by a smarter tool.
# Prints `file:line: message` for each violation and exits 1; exits 0 when there is none.
# Each rule is turned on by the change that makes it true, so a rule that is not here is not true yet.
# Run from anywhere; CI runs it in macos/ right after test-ci.sh.
set -uo pipefail
cd "$(dirname "$0")/.."
FAILED=0

# Rule: no Swift file is longer than 400 lines.
# Looks at every `*.swift` of the targets in LENGTH_TARGETS and prints the first line past the limit. A target joins the list when its files are split:
# `Carrier` joins when its long files are (the Carrier/ slices of the 400-line split).
# Ignores: nothing but the exclusion list, each with its reason; a file matching a pattern here is not counted:
#   *.generated.swift  generated by `pnpm design`, rewritten by the generator and never edited by hand, so its length is not a thing to split
LENGTH_TARGETS=("Sources/CarrierCore")
LENGTH_EXCLUSIONS=("*.generated.swift")
LENGTH_LIMIT=400
find_args=()
for pattern in "${LENGTH_EXCLUSIONS[@]}"; do find_args+=(! -name "$pattern"); done
find "${LENGTH_TARGETS[@]}" -name '*.swift' "${find_args[@]}" | sort |
  while IFS= read -r file; do
    lines=$(wc -l < "$file" | tr -d " ")
    [ "$lines" -gt "$LENGTH_LIMIT" ] && echo "$file:$((LENGTH_LIMIT + 1)): file has $lines lines, the limit is $LENGTH_LIMIT: split it by what it holds"
  done > /tmp/check-structure-length.$$
if [ -s /tmp/check-structure-length.$$ ]; then
  cat /tmp/check-structure-length.$$
  FAILED=1
fi
rm -f /tmp/check-structure-length.$$

# Rule: no two Swift files of one target share a name.
# A target is a folder of Sources/; the same name in two targets is allowed.
# Ignores: files that are not `*.swift`, and the test targets (Tests/ mirrors the sources and is outside this rule).
for target in Sources/*/; do
  find "$target" -name '*.swift' | sort | awk -F/ '
    { name = $NF; files[name] = files[name] " " $0; count[name]++ }
    END { for (n in count) if (count[n] > 1) { split(files[n], list, " "); for (i in list) print list[i] ":1: file name " n " is shared by " count[n] " files of one target" } }' | sort
done > /tmp/check-structure.$$
if [ -s /tmp/check-structure.$$ ]; then
  cat /tmp/check-structure.$$
  FAILED=1
fi
rm -f /tmp/check-structure.$$

# Rule: user defaults are read and written only under CarrierCore/Settings/.
# Flags `UserDefaults.standard`, and a call of the defaults' own accessors (set, object, string, bool, integer, double, float, data, array,
# dictionary, stringArray, url, removeObject) with a literal key (`forKey: "`), outside Sources/CarrierCore/Settings/.
# Ignores: comment lines; an injected `defaults: UserDefaults` parameter and its `= .standard` default; `didChangeNotification` observers;
# and `forKey: "` on something that is not the defaults (`removeValue` on a dictionary, `setValue` of key-value coding, `add` on a layer).
# Exclusion list, each with its reason; a file here is not scanned:
#   Sources/CarrierCore/Chat/ChatOptions.swift  the per-session state (`chat.options.<id>`, `chat.commands.<id>`, `chat.agent.<id>`): state of a session, not a preference
# Sparkle's own `SU*` keys are read by Sparkle, no code of the app names them; the last Settings page is `AppPreferences.lastSettingsPage`, under Settings/.
STATE_FILES=("Sources/CarrierCore/Chat/ChatOptions.swift")
grep -rnE 'UserDefaults\.standard|\b(set|object|string|bool|integer|double|float|data|array|dictionary|stringArray|url|removeObject)\(.*forKey: "' Sources --include='*.swift' |
  grep -v '^Sources/CarrierCore/Settings/' |
  grep -vE '^[^:]+:[0-9]+:\s*//' |
  while IFS= read -r hit; do
    file="${hit%%:*}"
    skip=0
    for state in "${STATE_FILES[@]}"; do [ "$file" = "$state" ] && skip=1; done
    [ "$skip" = 0 ] && echo "$hit" | sed -E 's/^([^:]+:[0-9]+):.*/\1: user defaults are touched outside CarrierCore\/Settings\/: use Preference and AppPreferences/'
  done > /tmp/check-structure-defaults.$$
if [ -s /tmp/check-structure-defaults.$$ ]; then
  cat /tmp/check-structure-defaults.$$
  FAILED=1
fi
rm -f /tmp/check-structure-defaults.$$

# Rule: a framework of the platform is touched only under Carrier/Platform/.
# Flags an import of Ghostty (GhosttyTerminal, GhosttyKit), FluidAudio, WhisperKit, Speech, AVFoundation, IOKit, Carbon, ApplicationServices, UserNotifications,
# Sparkle, MetricKit or ServiceManagement (a submodule, `Carbon.HIToolbox`, counts), and a call of a symbol with the prefix AX, SPU, AVAudio, IOPM, UN, MX or
# CGEvent: AppKit brings ApplicationServices in without an import, so the symbols are looked for too. Looks in every file of Sources/ outside Sources/Carrier/Platform/.
# Ignores: comments (from `//` to the end of the line) and string literals (`"AXTextField"` is a role's name, not a call), which are stripped before the lines are read.
# The prefixes UN and MX need a capital and a lower-case letter after them, so a constant such as `UNKNOWN` is not a symbol of UserNotifications.
FRAMEWORKS='Ghostty[A-Za-z]*|FluidAudio|WhisperKit|Speech|AVFoundation|IOKit|Carbon|ApplicationServices|UserNotifications|Sparkle|MetricKit|ServiceManagement'
SYMBOLS='AX[A-Z]|SPU[A-Z]|AVAudio|IOPM[A-Z]|UN[A-Z][a-z]|MX[A-Z][a-z]|CGEvent'
find Sources -name '*.swift' -not -path 'Sources/Carrier/Platform/*' | sort |
  while IFS= read -r file; do
    sed -E 's/"([^"\\]|\\.)*"//g; s|//.*$||' "$file" |
      grep -nE "^[[:space:]]*(@[A-Za-z_]+[[:space:]]+)*import[[:space:]]+($FRAMEWORKS)([^A-Za-z0-9_]|$)|(^|[^A-Za-z0-9_])($SYMBOLS)" |
      sed -E "s|^([0-9]+):.*|$file:\\1: a framework of the platform is used outside Carrier/Platform/: put it behind a protocol of CarrierCore/Platform/|"
  done > /tmp/check-structure-frameworks.$$
if [ -s /tmp/check-structure-frameworks.$$ ]; then
  cat /tmp/check-structure-frameworks.$$
  FAILED=1
fi
rm -f /tmp/check-structure-frameworks.$$

# Rule: every piece is named by an entry of the pieces gallery.
# A piece is a type declared at the top level of a file under Sources/Carrier/UI/ outside Tokens/ and Modifiers/: a `struct`, `enum`, `class`, `protocol` or
# `actor` that starts the line (with `final` or an attribute such as `@MainActor` before it), so a nested type does not count. An entry names it when its name
# is in quotes in a `GalleryEntry(` line of Sources/Carrier/Features/Settings/PiecesGallery*.swift: `GalleryEntry("SpinningRing", "RingLayer")` names both.
# Ignores: `private` and `fileprivate` types (they start with those words, so the pattern does not see them), and extensions, which declare no type.
GALLERY=(Sources/Carrier/Features/Settings/PiecesGallery*.swift)
grep -rnE '^(@[A-Za-z]+ )*(final )?(struct|enum|class|protocol|actor) [A-Za-z0-9_]+' Sources/Carrier/UI --include='*.swift' |
  grep -vE '^Sources/Carrier/UI/(Tokens|Modifiers)/' |
  while IFS= read -r hit; do
    name=$(echo "$hit" | sed -E 's/^[^:]+:[0-9]+:(@[A-Za-z]+ )*(final )?(struct|enum|class|protocol|actor) ([A-Za-z0-9_]+).*/\4/')
    grep -h 'GalleryEntry(' "${GALLERY[@]}" 2>/dev/null | grep -q "\"$name\"" ||
      echo "$hit" | sed -E "s/^([^:]+:[0-9]+):.*/\1: $name is a piece that no GalleryEntry of the pieces gallery names: add its entry to PiecesGallery<Kind>.swift/"
  done > /tmp/check-structure-gallery.$$
if [ -s /tmp/check-structure-gallery.$$ ]; then
  cat /tmp/check-structure-gallery.$$
  FAILED=1
fi
rm -f /tmp/check-structure-gallery.$$

exit $FAILED
