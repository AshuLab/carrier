#!/bin/bash
# Checks every structure rule of the spec (docs/specs/macos-app-as-the-base-for-a-web-front-end.md, section 9) and prints `file:line: message` for each violation.
# Greps, not a parser: a false alarm is fixed by renaming or by the rule's own ignore list, not by a smarter tool. Exits 1 on any violation, 0 on none.
# Every rule is always on: nothing here is switched off by a flag or a comment. Run from anywhere; CI runs it in macos/ right after test-ci.sh.
# Known limit: a literal passed positionally to a helper of our own (`item(menu, "Quit", ...)` in MainMenu) is seen by no rule: a grep does not know what the helper does with it.
# The rule "a piece names no type of an area" is not here: CarrierUI is a target, and the compiler refuses it.
set -uo pipefail
cd "$(dirname "$0")/.."
FAILED=0

# Rule: no Swift file under Sources/ is longer than 400 lines.
# Looks at every `*.swift` of the targets in LENGTH_TARGETS and prints the first line past the limit.
# Ignores: nothing but the list of exceptions, one entry per line as "pattern|reason". A file whose name matches a pattern is not counted. An entry with no reason
# on its line fails the script, so the list cannot grow without saying why. The list has one entry:
#   *.generated.swift  generated by `pnpm design`, rewritten by the generator and never edited by hand, so its length is not a thing to split
LENGTH_TARGETS=("Sources")
LENGTH_EXCLUSIONS=(
  "*.generated.swift|generated by pnpm design, rewritten by the generator and never edited by hand, so its length is not a thing to split"
)
LENGTH_LIMIT=400
find_args=()
for entry in "${LENGTH_EXCLUSIONS[@]}"; do
  pattern="${entry%%|*}"
  reason=""
  [[ "$entry" == *"|"* ]] && reason="${entry#*|}"
  if [ -z "${reason//[[:space:]]/}" ]; then
    entry_line=$(grep -nF -- "\"$entry\"" "$0" | head -1 | cut -d: -f1)
    echo "scripts/check-structure.sh:${entry_line:-1}: the length exception \"$pattern\" has no reason on its line: write it as \"pattern|reason\""
    FAILED=1
  fi
  find_args+=(! -name "$pattern")
done
find "${LENGTH_TARGETS[@]}" -name '*.swift' "${find_args[@]}" | sort |
  while IFS= read -r file; do
    lines=$(wc -l < "$file" | tr -d " ")
    [ "$lines" -gt "$LENGTH_LIMIT" ] && echo "$file:$((LENGTH_LIMIT + 1)): file has $lines lines, the limit is $LENGTH_LIMIT: split it by what it holds"
  done > /tmp/check-structure-length.$$
if [ -s /tmp/check-structure-length.$$ ]; then
  cat /tmp/check-structure-length.$$
  FAILED=1
fi
rm -f /tmp/check-structure-length.$$

# Rule: no two Swift files of one target share a name.
# A target is a folder of Sources/; the same name in two targets is allowed.
# Ignores: files that are not `*.swift`, and the test targets (Tests/ mirrors the sources and is outside this rule).
for target in Sources/*/; do
  find "$target" -name '*.swift' | sort | awk -F/ '
    { name = $NF; files[name] = files[name] " " $0; count[name]++ }
    END { for (n in count) if (count[n] > 1) { split(files[n], list, " "); for (i in list) print list[i] ":1: file name " n " is shared by " count[n] " files of one target" } }' | sort
done > /tmp/check-structure.$$
if [ -s /tmp/check-structure.$$ ]; then
  cat /tmp/check-structure.$$
  FAILED=1
fi
rm -f /tmp/check-structure.$$

# Rule: user defaults are read and written only under CarrierCore/Settings/.
# Flags `UserDefaults.standard`, and a call of the defaults' own accessors (set, object, string, bool, integer, double, float, data, array,
# dictionary, stringArray, url, removeObject) with a literal key (`forKey: "`), outside Sources/CarrierCore/Settings/.
# Ignores: comment lines; an injected `defaults: UserDefaults` parameter and its `= .standard` default; `didChangeNotification` observers;
# and `forKey: "` on something that is not the defaults (`removeValue` on a dictionary, `setValue` of key-value coding, `add` on a layer).
# No file is left out. The per-session state of Chat/ChatOptions.swift is stored under a key the code builds (`SessionKey.key(id)`), so no literal key is there to find.
# Sparkle's own `SU*` keys are read by Sparkle, no code of the app names them; the last Settings page is `AppPreferences.lastSettingsPage`, under Settings/.
grep -rnE 'UserDefaults\.standard|\b(set|object|string|bool|integer|double|float|data|array|dictionary|stringArray|url|removeObject)\(.*forKey: "' Sources --include='*.swift' |
  grep -v '^Sources/CarrierCore/Settings/' |
  grep -vE '^[^:]+:[0-9]+:\s*//' |
  sed -E 's/^([^:]+:[0-9]+):.*/\1: user defaults are touched outside CarrierCore\/Settings\/: use Preference and AppPreferences/' > /tmp/check-structure-defaults.$$
if [ -s /tmp/check-structure-defaults.$$ ]; then
  cat /tmp/check-structure-defaults.$$
  FAILED=1
fi
rm -f /tmp/check-structure-defaults.$$

# Rule: no literal size or colour outside CarrierUI/Tokens/.
# A literal number as the value of `cornerRadius:` or `spacing:`, in the arguments of `.padding(` (with or without an edge), and a `Color(red:`, `NSColor(red:`,
# `Color(hue:` or `Color(white:` at all, in every file of Sources/ outside Sources/CarrierUI/Tokens/; a size is a token (`Tokens.Space`, `Tokens.Radius`), a colour a token or a system colour.
# Ignores: comments and string literals, which are stripped before the lines are read; and a number that is the operand of an operator (`-width / 2`, `index > 0`):
# that is a computation on a measure, not a size. Only a number standing as a whole argument or as a branch of `? :` counts (`.padding(8)`, `.padding(.top, large ? 24 : 16)`).
# Sources/CarrierUI/Tokens/ is where the numbers live, so it is not read.
find Sources -name '*.swift' -not -path 'Sources/CarrierUI/Tokens/*' | sort |
  while IFS= read -r file; do
    perl -0777 -ne '
      my $inner = qr/(?:[^()]|\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\))*/;
      my $s = $_;
      $s =~ s{("(?:[^"\\\n]|\\.)*")|(//[^\n]*)}{defined $1 ? "\"\"" : ""}ge;
      my $literal = qr/(?:^|[(,:?])\s*-?[0-9]/;
      while ($s =~ /\b(?:cornerRadius|spacing):([^,)\n]*)|\.padding\(($inner)\)|\b((?:NS)?Color\((?:red|hue|white):)/g) {
        my ($value, $args, $color, $at, $len) = ($1, $2, $3, $-[0], $+[0] - $-[0]);
        next unless defined $color or (defined $value and $value =~ /^\s*-?[0-9]|[?:]\s*-?[0-9]/) or (defined $args and $args =~ $literal);
        my $line = 1 + (substr($s, 0, $at) =~ tr/\n//);
        my $what = substr($s, $at, $len); $what =~ s/\s+/ /g;
        print "$ARGV:$line: a literal size or colour outside CarrierUI/Tokens/ ($what): use a token of Tokens.Space, Tokens.Radius or the colour tokens\n";
      }
' "$file" | sed "s|^-:|$file:|"
  done > /tmp/check-structure-look.$$
if [ -s /tmp/check-structure-look.$$ ]; then
  cat /tmp/check-structure-look.$$
  FAILED=1
fi
rm -f /tmp/check-structure-look.$$

# Rule: a framework of the platform is touched only under Carrier/Platform/.
# Flags an import of Ghostty (GhosttyTerminal, GhosttyKit), FluidAudio, WhisperKit, Speech, AVFoundation, IOKit, Carbon, ApplicationServices, UserNotifications,
# Sparkle, MetricKit or ServiceManagement (a submodule, `Carbon.HIToolbox`, counts), and a call of a symbol with the prefix AX, SPU, AVAudio, IOPM, UN, MX or
# CGEvent: AppKit brings ApplicationServices in without an import, so the symbols are looked for too. Looks in every file of Sources/ outside Sources/Carrier/Platform/.
# Ignores: comments (from `//` to the end of the line) and string literals (`"AXTextField"` is a role's name, not a call), which are stripped before the lines are read.
# The prefixes UN and MX need a capital and a lower-case letter after them, so a constant such as `UNKNOWN` is not a symbol of UserNotifications.
FRAMEWORKS='Ghostty[A-Za-z]*|FluidAudio|WhisperKit|Speech|AVFoundation|IOKit|Carbon|ApplicationServices|UserNotifications|Sparkle|MetricKit|ServiceManagement'
SYMBOLS='AX[A-Z]|SPU[A-Z]|AVAudio|IOPM[A-Z]|UN[A-Z][a-z]|MX[A-Z][a-z]|CGEvent'
find Sources -name '*.swift' -not -path 'Sources/Carrier/Platform/*' | sort |
  while IFS= read -r file; do
    sed -E 's/"([^"\\]|\\.)*"//g; s|//.*$||' "$file" |
      grep -nE "^[[:space:]]*(@[A-Za-z_]+[[:space:]]+)*import[[:space:]]+($FRAMEWORKS)([^A-Za-z0-9_]|$)|(^|[^A-Za-z0-9_])($SYMBOLS)" |
      sed -E "s|^([0-9]+):.*|$file:\\1: a framework of the platform is used outside Carrier/Platform/: put it behind a protocol of CarrierCore/Platform/|"
  done > /tmp/check-structure-frameworks.$$
if [ -s /tmp/check-structure-frameworks.$$ ]; then
  cat /tmp/check-structure-frameworks.$$
  FAILED=1
fi
rm -f /tmp/check-structure-frameworks.$$

# Rule: every piece is named by an entry of the pieces gallery.
# A piece is a type declared at the top level of a file under Sources/CarrierUI/ outside Tokens/ and Modifiers/: a `struct`, `enum`, `class`, `protocol` or
# `actor` that starts the line (with `public`, `final` or an attribute such as `@MainActor` before it), so a nested type does not count. An entry names it when its name
# is in quotes in a `GalleryEntry(` line of Sources/Carrier/Features/Settings/PiecesGallery*.swift: `GalleryEntry("SpinningRing", "RingLayer")` names both.
# Ignores: `private` and `fileprivate` types (they start with those words, so the pattern does not see them), and extensions, which declare no type.
GALLERY=(Sources/Carrier/Features/Settings/PiecesGallery*.swift)
grep -rnE '^(@[A-Za-z]+ )*(public )?(final )?(struct|enum|class|protocol|actor) [A-Za-z0-9_]+' Sources/CarrierUI --include='*.swift' |
  grep -vE '^Sources/CarrierUI/(Tokens|Modifiers)/' |
  while IFS= read -r hit; do
    name=$(echo "$hit" | sed -E 's/^[^:]+:[0-9]+:(@[A-Za-z]+ )*(public )?(final )?(struct|enum|class|protocol|actor) ([A-Za-z0-9_]+).*/\5/')
    grep -h 'GalleryEntry(' "${GALLERY[@]}" 2>/dev/null | grep -q "\"$name\"" ||
      echo "$hit" | sed -E "s/^([^:]+:[0-9]+):.*/\1: $name is a piece that no GalleryEntry of the pieces gallery names: add its entry to PiecesGallery<Kind>.swift/"
  done > /tmp/check-structure-gallery.$$
if [ -s /tmp/check-structure-gallery.$$ ]; then
  cat /tmp/check-structure-gallery.$$
  FAILED=1
fi
rm -f /tmp/check-structure-gallery.$$

# Rule: no user-facing string literal in the areas whose texts are copy keys.
# A literal passed to `Text`, `Label`, `Button`, `Toggle`, `TextField` or `SecureField`, to `.help`, `.accessibilityLabel`, `.accessibilityValue`, `.accessibilityHint`,
# `.navigationTitle`, `.alert`, `.confirmationDialog` or `setAccessibilityLabel`, given to a `title:` or `withTitle:` label, or assigned to `.title`, `.messageText`,
# `.informativeText`, `.toolTip`, `.subtitle`, `.placeholderString` or `.accessibilityLabel`, the call possibly over several lines. Looks at the files of COPY_AREAS, and says
# which literal and where; a text is a key of design/copy/ read through `Copy` (docs/adr/0054).
# Ignores: comments (from `//` to the end of the line), the empty string, and a string with no letter once its interpolations are taken out (spaces, punctuation, `"\(x)"`).
# COPY_AREAS is the whole of Sources/Carrier, Sources/CarrierUI and Sources/CarrierCore: no file or folder is left out, the two fixture galleries and the generated files included.
COPY_AREAS=(Sources/Carrier Sources/CarrierUI Sources/CarrierCore)
find "${COPY_AREAS[@]}" -name '*.swift' | sort |
  while IFS= read -r file; do
    perl -0777 -ne '
      my $inner = qr/(?:[^()]|\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\))*/;
      my $str = qr/"(?:[^"\\\n]|\\\($inner\)|\\.)*"/;
      my $s = $_;
      $s =~ s{($str)|(//[^\n]*)}{defined $1 ? $1 : ""}ge;
      # the AppKit calls: withTitle labels, setAccessibilityLabel, and a literal assigned to title, messageText, informativeText, toolTip, subtitle, placeholderString or an accessibility text
      my $call = qr/(?:\b(?:Text|Label|Button|Toggle|TextField|SecureField)|\.(?:help|accessibilityLabel|accessibilityValue|accessibilityHint|navigationTitle|alert|confirmationDialog)|\bset(?:AccessibilityLabel|AccessibilityHelp|AccessibilityValueDescription))\(\s*|\b(?:title|withTitle):\s*|\.(?:title|messageText|informativeText|toolTip|subtitle|placeholderString|accessibilityLabel|accessibilityHint)\s*=\s*/;
      while ($s =~ /$call($str)/g) {
        my ($text, $at) = ($1, $-[0]);
        (my $words = $text) =~ s/\\\($inner\)//g;
        next unless $words =~ /[A-Za-z]/;
        my $line = 1 + (substr($s, 0, $at) =~ tr/\n//);
        print "$ARGV:$line: $text is a user-facing literal in an area whose texts are copy keys: add the key to design/copy/en.json and es.json and read it through Copy\n";
      }
' "$file" | sed "s|^-:|$file:|"
  done > /tmp/check-structure-copy.$$
if [ -s /tmp/check-structure-copy.$$ ]; then
  cat /tmp/check-structure-copy.$$
  FAILED=1
fi
rm -f /tmp/check-structure-copy.$$

exit $FAILED
