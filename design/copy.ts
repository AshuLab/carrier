// The copy source: parse, validate and emit the restricted ICU MessageFormat of ADR 0054.
// Accepted: {name}, {name, number}, {name, plural, ...} with =0, one, two, few, many, other and #, and {name, select, ...}.
// A plural or select may hold one more plural or select; a message has one select at most.

export const SOURCE_LANGUAGE = 'en';
export const LANGUAGES = ['en', 'es'] as const;
export type Language = (typeof LANGUAGES)[number];

export const GENERATED_HEADER = '// Generated by design/generate.ts from design/; do not edit.';

export type Kind = 'string' | 'number' | 'select';

export type Node =
  | { type: 'text'; value: string }
  | { type: 'arg'; name: string }
  | { type: 'number'; name: string }
  | { type: 'pound' }
  | { type: 'plural'; name: string; cases: Case[] }
  | { type: 'select'; name: string; cases: Case[] };

export interface Case {
  selector: string;
  nodes: Node[];
}

/** A refusal of the source: its message names the key (and the language when it is one language's). */
export class CopyError extends Error {}

const IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/;
const KEY = /^[a-z][A-Za-z0-9]*$/;
const PLURAL_CATEGORIES = ['one', 'two', 'few', 'many', 'other'];
const UNSUPPORTED_TYPES = ['selectordinal', 'date', 'time'];

// Parsing

class Parser {
  pos = 0;
  src: string;
  where: string;

  constructor(src: string, where: string) {
    this.src = src;
    this.where = where;
  }

  fail(reason: string): never {
    throw new CopyError(`${this.where}: ${reason} (at character ${this.pos + 1})`);
  }

  skipSpace(): void {
    while (/\s/.test(this.src[this.pos] ?? '')) this.pos++;
  }

  expect(char: string): void {
    this.skipSpace();
    if (this.src[this.pos] !== char) this.fail(`expected "${char}"`);
    this.pos++;
  }

  word(pattern: RegExp, what: string): string {
    this.skipSpace();
    const match = pattern.exec(this.src.slice(this.pos));
    if (match === null) this.fail(`expected ${what}`);
    this.pos += match[0].length;
    return match[0];
  }

  /** `depth` counts the plurals and selects around this text; `inPlural` makes `#` the number. */
  nodes(depth: number, inPlural: boolean, closing: boolean): Node[] {
    const nodes: Node[] = [];
    let text = '';
    const flush = () => {
      if (text !== '') nodes.push({ type: 'text', value: text });
      text = '';
    };
    while (this.pos < this.src.length) {
      const char = this.src[this.pos] as string;
      if (char === '}') {
        if (closing) break;
        this.fail('unbalanced "}"');
      } else if (char === '{') {
        flush();
        nodes.push(this.argument(depth, inPlural));
        continue;
      } else if (char === "'") {
        this.fail('apostrophe quoting is not supported');
      } else if (char === '#' && inPlural) {
        flush();
        nodes.push({ type: 'pound' });
      } else {
        text += char;
      }
      this.pos++;
    }
    if (closing && this.pos >= this.src.length) this.fail('missing "}"');
    flush();
    return nodes;
  }

  argument(depth: number, inPlural: boolean): Node {
    this.expect('{');
    const name = this.word(/^[A-Za-z_][A-Za-z0-9_]*/, 'an argument name');
    this.skipSpace();
    if (this.src[this.pos] === '}') {
      this.pos++;
      return { type: 'arg', name };
    }
    this.expect(',');
    const type = this.word(/^[A-Za-z]+/, 'an argument type');
    if (UNSUPPORTED_TYPES.includes(type)) this.fail(`${type} is not supported`);
    if (type === 'number') {
      this.skipSpace();
      if (this.src[this.pos] === ',') this.fail('number styles are not supported');
      this.expect('}');
      return { type: 'number', name };
    }
    if (type !== 'plural' && type !== 'select') this.fail(`unknown argument type "${type}"`);
    if (depth >= 2) this.fail('nesting deeper than one level is not supported');
    this.expect(',');
    const cases: Case[] = [];
    for (;;) {
      this.skipSpace();
      if (this.src[this.pos] === '}') break;
      const selector = this.word(/^[^\s{}]+/, 'a branch name');
      this.checkSelector(type, selector, cases);
      this.expect('{');
      cases.push({ selector, nodes: this.nodes(depth + 1, type === 'plural' ? true : inPlural, true) });
      this.expect('}');
    }
    this.pos++;
    if (cases.length === 0) this.fail(`${type} without branches`);
    if (type === 'plural' && !cases.some((branch) => branch.selector === 'other')) this.fail('plural without "other"');
    return { type, name, cases };
  }

  checkSelector(type: 'plural' | 'select', selector: string, seen: Case[]): void {
    if (seen.some((branch) => branch.selector === selector)) this.fail(`duplicate branch "${selector}"`);
    if (type === 'select') {
      if (!IDENTIFIER.test(selector)) this.fail(`select branch "${selector}" is not an identifier`);
      return;
    }
    if (selector.startsWith('offset:')) this.fail('plural offset is not supported');
    if (selector.startsWith('=')) {
      if (selector !== '=0') this.fail(`"${selector}" is not supported, only =0`);
      return;
    }
    if (selector === 'zero') this.fail('"zero" is not supported, use =0');
    if (!PLURAL_CATEGORIES.includes(selector)) this.fail(`unknown plural category "${selector}"`);
  }
}

export function parseMessage(key: string, language: string, message: string): Node[] {
  const parser = new Parser(message, `copy key "${key}" (${language})`);
  return parser.nodes(0, false, false);
}

// Analysis

export interface Analysis {
  /** In order of first appearance. */
  args: Map<string, Kind>;
  select: string | null;
  /** The arguments each select branch uses. */
  branches: Map<string, string[]>;
}

function argsOf(nodes: Node[], into: Set<string> = new Set()): Set<string> {
  for (const node of nodes) {
    if (node.type === 'arg' || node.type === 'number') into.add(node.name);
    if (node.type === 'plural' || node.type === 'select') {
      into.add(node.name);
      for (const branch of node.cases) argsOf(branch.nodes, into);
    }
  }
  return into;
}

export function analyze(key: string, language: string, nodes: Node[]): Analysis {
  const where = `copy key "${key}" (${language})`;
  const analysis: Analysis = { args: new Map(), select: null, branches: new Map() };
  const record = (name: string, kind: Kind) => {
    const known = analysis.args.get(name);
    if (known !== undefined && known !== kind) throw new CopyError(`${where}: argument "${name}" is used as ${known} and as ${kind}`);
    analysis.args.set(name, kind);
  };
  const walk = (list: Node[]) => {
    for (const node of list) {
      if (node.type === 'arg') record(node.name, 'string');
      if (node.type === 'number') record(node.name, 'number');
      if (node.type === 'plural') {
        record(node.name, 'number');
        for (const branch of node.cases) walk(branch.nodes);
      }
      if (node.type === 'select') {
        if (analysis.select !== null) throw new CopyError(`${where}: more than one select in a message is not supported`);
        record(node.name, 'select');
        analysis.select = node.name;
        for (const branch of node.cases) {
          analysis.branches.set(branch.selector, [...argsOf(branch.nodes)].sort());
          walk(branch.nodes);
        }
      }
    }
  };
  walk(nodes);
  return analysis;
}

// The two languages together

export interface CompiledKey {
  key: string;
  /** The English analysis: its argument order is the function's. */
  analysis: Analysis;
  messages: Record<Language, Node[]>;
}

export interface CompiledCopy {
  keys: CompiledKey[];
}

const describeArgs = (analysis: Analysis) => [...analysis.args].map(([name, kind]) => `${name}: ${kind}`).sort().join(', ');

function describeBranches(analysis: Analysis): string {
  return [...analysis.branches].map(([branch, args]) => `${branch}(${args.join(' ')})`).sort().join(' ');
}

/** Parses and checks both languages; English is the source, so a key Spanish lacks, or has more, fails. */
export function compileCopy(sources: Record<Language, Record<string, string>>): CompiledCopy {
  const source = sources[SOURCE_LANGUAGE];
  const keys: CompiledKey[] = [];
  for (const language of LANGUAGES) {
    for (const key of Object.keys(sources[language])) {
      if (!(key in source)) throw new CopyError(`copy key "${key}" is in ${language} and not in ${SOURCE_LANGUAGE}`);
    }
  }
  for (const key of Object.keys(source)) {
    if (!KEY.test(key)) throw new CopyError(`copy key "${key}" is not lowerCamelCase`);
    const messages = {} as Record<Language, Node[]>;
    const analyses = {} as Record<Language, Analysis>;
    for (const language of LANGUAGES) {
      const text = sources[language][key];
      if (text === undefined) throw new CopyError(`copy key "${key}" is missing in ${language}`);
      messages[language] = parseMessage(key, language, text);
      analyses[language] = analyze(key, language, messages[language]);
    }
    const base = analyses[SOURCE_LANGUAGE];
    for (const language of LANGUAGES) {
      const other = analyses[language];
      if (describeArgs(other) !== describeArgs(base)) {
        throw new CopyError(`copy key "${key}" (${language}): arguments (${describeArgs(other)}) differ from ${SOURCE_LANGUAGE} (${describeArgs(base)})`);
      }
      if (describeBranches(other) !== describeBranches(base)) {
        throw new CopyError(`copy key "${key}" (${language}): select branches (${describeBranches(other)}) differ from ${SOURCE_LANGUAGE} (${describeBranches(base)})`);
      }
    }
    keys.push({ key, analysis: base, messages });
  }
  return { keys };
}

// Emitting

const pascal = (name: string) => name.charAt(0).toUpperCase() + name.slice(1);

/** The message with its select replaced by one branch's text. */
function resolveSelect(nodes: Node[], branch: string): Node[] {
  return nodes.flatMap((node): Node[] => {
    if (node.type === 'select') return resolveSelect(node.cases.find((candidate) => candidate.selector === branch)?.nodes ?? [], branch);
    if (node.type === 'plural') return [{ ...node, cases: node.cases.map((c) => ({ ...c, nodes: resolveSelect(c.nodes, branch) })) }];
    return [node];
  });
}

interface Variant {
  /** `.branch` for a select's branch, else empty. */
  suffix: string;
  branch: string | null;
  /** The arguments the catalog key carries, in the function's order. */
  args: string[];
}

function variants(compiled: CompiledKey): Variant[] {
  const { analysis } = compiled;
  const order = [...analysis.args.keys()];
  if (analysis.select === null) return [{ suffix: '', branch: null, args: order }];
  return [...analysis.branches].map(([branch, used]) => ({
    suffix: `.${branch}`,
    branch,
    args: order.filter((name) => used.includes(name)),
  }));
}

function nodesOf(compiled: CompiledKey, language: Language, variant: Variant): Node[] {
  const nodes = compiled.messages[language];
  return variant.branch === null ? nodes : resolveSelect(nodes, variant.branch);
}

const specifier = (kind: Kind | undefined) => (kind === 'number' ? 'lld' : '@');

function catalogKey(compiled: CompiledKey, variant: Variant): string {
  const specifiers = variant.args.map((name) => `%${specifier(compiled.analysis.args.get(name))}`);
  return [`${compiled.key}${variant.suffix}`, ...specifiers].join(' ');
}

interface Unit {
  stringUnit: { state: 'translated'; value: string };
}
interface Substitution {
  argNum: number;
  formatSpecifier: 'lld';
  variations: { plural: Record<string, Unit> };
}

function localization(compiled: CompiledKey, variant: Variant, language: Language) {
  const substitutions: Record<string, Substitution> = {};
  const unit = (value: string): Unit => ({ stringUnit: { state: 'translated', value } });
  const render = (nodes: Node[]): string =>
    nodes
      .map((node) => {
        if (node.type === 'text') return node.value.replaceAll('%', '%%');
        if (node.type === 'pound') return '%arg';
        if (node.type === 'select') throw new Error('a select is resolved before it is rendered');
        const position = variant.args.indexOf(node.name) + 1;
        if (node.type === 'arg') return `%${position}$@`;
        if (node.type === 'number') return `%${position}$lld`;
        let name = node.name;
        for (let n = 2; name in substitutions; n++) name = `${node.name}${n}`;
        const substitution: Substitution = { argNum: position, formatSpecifier: 'lld', variations: { plural: {} } };
        substitutions[name] = substitution;
        for (const branch of node.cases) {
          substitution.variations.plural[branch.selector === '=0' ? 'zero' : branch.selector] = unit(render(branch.nodes));
        }
        return `%#@${name}@`;
      })
      .join('');
  const value = render(nodesOf(compiled, language, variant));
  return Object.keys(substitutions).length === 0 ? unit(value) : { ...unit(value), substitutions };
}

/** Localizable.xcstrings: a plural is a substitution, `=0` is `zero`, each select branch is a key of its own, specifiers are positional. */
export function emitCatalog(copy: CompiledCopy): string {
  const strings: Record<string, unknown> = {};
  for (const compiled of copy.keys) {
    for (const variant of variants(compiled)) {
      const localizations: Record<string, unknown> = {};
      for (const language of LANGUAGES) localizations[language] = localization(compiled, variant, language);
      strings[catalogKey(compiled, variant)] = { extractionState: 'manual', localizations };
    }
  }
  const sorted = Object.fromEntries(Object.entries(strings).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  return `${JSON.stringify({ sourceLanguage: SOURCE_LANGUAGE, strings: sorted, version: '1.0' }, null, 2)}\n`;
}

const swiftType = (compiled: CompiledKey, name: string) => {
  const kind = compiled.analysis.args.get(name);
  return kind === 'number' ? 'Int' : kind === 'select' ? pascal(compiled.key) : 'String';
};

/** Copy.generated.swift: a typed function per key, reading `carrierResources` and never `Bundle.module`. */
export function emitSwift(copy: CompiledCopy): string {
  const lines = [
    GENERATED_HEADER,
    '',
    'import Foundation',
    '',
    'public enum Copy {',
    "    /// One language's catalog, for tests; the app passes none and gets the language macOS gives it.",
    '    public static func bundle(_ language: String) -> Bundle {',
    '        carrierResources.path(forResource: language, ofType: "lproj").flatMap(Bundle.init(path:)) ?? carrierResources',
    '    }',
  ];
  for (const compiled of copy.keys) {
    const { key, analysis } = compiled;
    lines.push('');
    if (analysis.select !== null) {
      const cases = [...analysis.branches.keys()].map((branch) => `case ${branch}`).join('; ');
      lines.push(`    public enum ${pascal(key)}: Sendable { ${cases} }`);
    }
    const params = [...analysis.args.keys()].map((name) => `${name}: ${swiftType(compiled, name)}`);
    params.push('bundle: Bundle? = nil', 'locale: Locale = .current');
    lines.push(`    public static func ${key}(${params.join(', ')}) -> String {`);
    const call = (variant: Variant) => {
      const interpolations = variant.args.map((name) => ` \\(${name})`).join('');
      return `String(localized: "${key}${variant.suffix}${interpolations}", bundle: bundle ?? carrierResources, locale: locale)`;
    };
    if (analysis.select === null) {
      lines.push(`        ${call(variants(compiled)[0] as Variant)}`);
    } else {
      lines.push(`        switch ${analysis.select} {`);
      for (const variant of variants(compiled)) lines.push(`        case .${variant.branch}: return ${call(variant)}`);
      lines.push('        }');
    }
    lines.push('    }');
  }
  lines.push('}', '');
  return lines.join('\n');
}

const TYPESCRIPT_PRELUDE = `${GENERATED_HEADER}

export type Language = ${LANGUAGES.map((language) => `'${language}'`).join(' | ')};

const languages: readonly string[] = ${JSON.stringify(LANGUAGES).replaceAll('"', "'").replaceAll(',', ', ')};

/** The language of a locale such as "es-AR"; a language with no words here reads as ${SOURCE_LANGUAGE}. */
function languageOf(locale: string): Language {
  const language = locale.split(/[-_]/)[0] ?? '';
  return (languages.includes(language) ? language : '${SOURCE_LANGUAGE}') as Language;
}

function formatNumber(locale: string, value: number): string {
  return new Intl.NumberFormat(locale).format(value);
}

function pluralOf(locale: string, value: number, cases: { other: string; [selector: string]: string }): string {
  const exact = value === 0 ? cases['=0'] : undefined;
  return exact ?? cases[new Intl.PluralRules(locale).select(value)] ?? cases.other;
}
`;

function tsExpression(nodes: Node[], pluralArg: string | null): string {
  if (nodes.length === 0) return "''";
  const parts = nodes.map((node) => {
    if (node.type === 'text') return JSON.stringify(node.value);
    if (node.type === 'arg') return `args.${node.name}`;
    if (node.type === 'number') return `formatNumber(locale, args.${node.name})`;
    if (node.type === 'pound') return `formatNumber(locale, args.${pluralArg})`;
    const cases = node.cases.map((branch) => `${JSON.stringify(branch.selector)}: ${tsExpression(branch.nodes, node.type === 'plural' ? node.name : pluralArg)}`);
    if (node.type === 'plural') return `pluralOf(locale, args.${node.name}, { ${cases.join(', ')} })`;
    return `({ ${cases.join(', ')} })[args.${node.name}]`;
  });
  return parts.join(' + ');
}

/** copy.ts for the web: a typed function per key; numbers go through Intl.NumberFormat and plurals through Intl.PluralRules. */
export function emitTypeScript(copy: CompiledCopy): string {
  const blocks = [TYPESCRIPT_PRELUDE];
  for (const compiled of copy.keys) {
    const { key, analysis } = compiled;
    const types = [...analysis.args].map(([name, kind]) => {
      if (kind === 'number') return `${name}: number`;
      if (kind === 'string') return `${name}: string`;
      return `${name}: ${[...analysis.branches.keys()].map((branch) => `'${branch}'`).join(' | ')}`;
    });
    const params = types.length === 0 ? 'locale: string' : `locale: string, args: { ${types.join('; ')} }`;
    const cases = LANGUAGES.map((language) => `    case '${language}': return ${tsExpression(compiled.messages[language], null)};`);
    blocks.push(`export function ${key}(${params}): string {\n  switch (languageOf(locale)) {\n${cases.join('\n')}\n  }\n}\n`);
  }
  return blocks.join('\n');
}
